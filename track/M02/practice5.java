public class practice5 {
    public static void main(String[] args) {
        int num = 10;
        // int num = -1 it will print negative
        // int num = 0 it will print zero
        if (num > 0) {
            System.out.println("Positive");
        } else if (num < 0) {
            System.out.println("Negative");
        } else {
            System.out.println("Zero");
        }
    }
}
